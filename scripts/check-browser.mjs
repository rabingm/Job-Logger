import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
const output = 'packages/resume-core/dist/pdf-review';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ acceptDownloads: true, viewport: { width: 1100, height: 950 } });
  for (const template of ['clean', 'modern-split', 'soft-accent']) {
    await page.goto(`${process.env.PREVIEW_URL || 'http://127.0.0.1:3001'}/demo?template=${template}&contact=hidden`);
    assert.equal(await page.locator('article').getAttribute('class'), `resume template-${template}`);
    const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download PDF' }).click();
    const file = `${output}/browser-${template}.pdf`; await (await download).saveAs(file);
    const text = execFileSync('pdftotext', [file, '-'], { encoding: 'utf8' });
    assert.match(text, /Alex Morgan/); assert.doesNotMatch(text, /alex@example.com|Fictional|Resume App|localhost/);
    await page.screenshot({ path: `${output}/web-${template}.png`, fullPage: true });
  }
  await page.goto(process.env.EXPO_URL || 'http://localhost:8081');
  await page.getByRole('button', { name: 'Explore fictional example' }).click();
  await page.getByRole('tab', { name: 'Profile' }).click();
  await page.getByRole('button', { name: 'Edit profile & sections' }).click();
  await page.getByRole('textbox', { name: 'Phone (optional)', exact: true }).fill('+61 400 123 456');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('tab', { name: 'Log' }).click();
  await page.getByRole('textbox', { name: 'New achievement' }).fill('Browser verified achievement');
  await page.getByRole('button', { name: '+ Add date, tags, tools or role', exact: true }).click();
  await page.getByRole('textbox', { name: 'Tools used (optional, comma separated)' }).fill('Excel, SQL');
  await page.getByRole('button', { name: '+ Save achievement', exact: true }).click();
  await page.reload(); await page.getByText('Browser verified achievement', { exact: true }).waitFor();
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('resume-app.fictional-demo.v1')));
  assert.equal(state.schemaVersion, 2); assert.equal(state.activities[0].roleId, 'role-1'); assert.deepEqual(state.activities[0].tools, ['Excel', 'SQL']);
  await page.getByRole('button', { name: 'Archive', exact: true }).first().click();
  await page.getByRole('switch', { name: 'Show archived achievements' }).click();
  await page.getByRole('heading', { name: 'Operations Specialist · Example Studio' }).waitFor();
  await page.getByRole('button', { name: 'Restore', exact: true }).click();
  await page.getByRole('tab', { name: 'Profile' }).click();
  await page.getByRole('button', { name: '+ Add role', exact: true }).click();
  await page.getByRole('textbox', { name: 'Role title', exact: true }).fill('Volunteer coordinator');
  await page.getByRole('textbox', { name: 'Employer', exact: true }).fill('Example charity');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('button', { name: 'Use as default current role', exact: true }).click();
  await page.getByRole('tab', { name: 'Log' }).click();
  await page.getByRole('textbox', { name: 'New achievement' }).fill('New default role achievement');
  await page.getByRole('button', { name: '+ Save achievement', exact: true }).click();
  await page.getByText('Saved on this device', { exact: true }).waitFor();
  const updated = await page.evaluate(() => JSON.parse(localStorage.getItem('resume-app.fictional-demo.v1')));
  assert.equal(updated.activities[0].roleId, updated.defaultRoleId);
  assert.equal(updated.roles.find(r => r.id === updated.defaultRoleId).employer, 'Example charity');
  await page.getByRole('tab', { name: 'My résumés' }).click();
  await page.getByRole('button', { name: 'Open résumé' }).click();
  await page.getByRole('button', { name: 'Soft Accent', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export PDF', exact: true }).click();
  const file = `${output}/browser-expo.pdf`; await (await download).saveAs(file);
  const text = execFileSync('pdftotext', [file, '-'], { encoding: 'utf8' });
  assert.match(text, /\+61 400 123 456/); assert.doesNotMatch(text, /Excel|SQL|Browser verified achievement|Resume App/);
  await page.screenshot({ path: `${output}/expo-template.png`, fullPage: true });
  console.log('PASS: three Next template downloads and Expo profile, capture/tools persistence, template selection and PDF download.');
} finally { await browser.close(); }
